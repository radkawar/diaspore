local CASE_VARIANTS = {}
for _, group in ipairs(CASE_GROUPS) do
  for _, cp in ipairs(group) do CASE_VARIANTS[cp] = group end
end

local function in_ranges(cp, ranges)
  local lo, hi = 1, #ranges // 2
  while lo <= hi do
    local mid = (lo + hi) // 2
    if cp < ranges[mid * 2 - 1] then hi = mid - 1
    elseif cp > ranges[mid * 2] then lo = mid + 1
    else return true end
  end
  return false
end

local function ascii_mode(flags, binary)
  return binary or flags & ASCII ~= 0
end

local function category(cp, name, flags, binary)
  if cp == nil then return false end
  local ascii = ascii_mode(flags, binary)
  local positive
  local key = name:lower()
  if key == "d" then
    positive = ascii and cp >= 48 and cp <= 57 or not ascii and in_ranges(cp, DIGIT_RANGES)
  elseif key == "s" then
    positive = ascii and (cp == 32 or cp >= 9 and cp <= 13) or not ascii and H.is_space_cp(cp)
  else
    positive = ascii and (cp == 95 or cp >= 48 and cp <= 57
      or cp >= 65 and cp <= 90 or cp >= 97 and cp <= 122)
      or not ascii and in_ranges(cp, WORD_RANGES)
  end
  if key ~= name then return not positive end
  return positive
end

local function equal_cp(a, b, flags, binary)
  if a == b then return true end
  if flags & IGNORECASE == 0 then return false end
  if ascii_mode(flags, binary) then
    if a >= 65 and a <= 90 then a = a + 32 end
    if b >= 65 and b <= 90 then b = b + 32 end
    return a == b
  end
  local variants = CASE_VARIANTS[a]
  return variants ~= nil and variants == CASE_VARIANTS[b]
end

local function in_case_range(cp, lo, hi, flags, binary)
  if cp >= lo and cp <= hi then return true end
  if flags & IGNORECASE == 0 then return false end
  if ascii_mode(flags, binary) then
    if cp >= 65 and cp <= 90 then cp = cp + 32
    elseif cp >= 97 and cp <= 122 then cp = cp - 32
    else return false end
    return cp >= lo and cp <= hi
  end
  for _, variant in ipairs(CASE_VARIANTS[cp] or {}) do
    if variant >= lo and variant <= hi then return true end
  end
  return false
end

local function character_class(node, cp, binary)
  local matched = false
  for _, item in ipairs(node.items) do
    if item.op == "category" then
      matched = category(cp, item.name, node.flags, binary)
    else
      matched = in_case_range(cp, item.lo, item.hi, node.flags, binary)
    end
    if matched then break end
  end
  if node.negate then return not matched end
  return matched
end

local function string_data(value, what)
  if type(value) == "string" then return value, false end
  if type(value) == "table" and value.kind == "bytes" then return value.b, true end
  throw("TypeError", what .. " must be a string or bytes")
end

local function units(data, binary)
  local cps, offsets = {}, {}
  if binary then
    for i = 1, #data do cps[i], offsets[i] = data:byte(i), i end
  else
    for offset, cp in utf8.codes(data, true) do
      cps[#cps + 1], offsets[#offsets + 1] = cp, offset
    end
  end
  offsets[#cps + 1] = #data + 1
  return cps, offsets
end

local function text_value(data, binary)
  if binary then return V.bytes(data) end
  return data
end

local function integer(value, name)
  local n = V.as_index(value)
  if n == nil then throw("TypeError", name .. " must be an integer") end
  return V.to_size(n)
end

local function arguments(name, args, kw, names, required, defaults)
  if #args > #names then throw("TypeError", name .. "() takes at most " .. #names .. " arguments") end
  local bound = {}
  for i, value in ipairs(args) do bound[i] = value end
  for _, pair in ipairs(kw) do
    local found
    for i, key in ipairs(names) do
      if pair.k == key then
        if bound[i] ~= nil then throw("TypeError", name .. "() got multiple values for '" .. key .. "'") end
        bound[i], found = pair.v, true
        break
      end
    end
    if not found then throw("TypeError", name .. "() got an unexpected keyword argument '" .. pair.k .. "'") end
  end
  for i, key in ipairs(names) do
    if bound[i] == nil then
      if i <= required then throw("TypeError", name .. "() missing required argument '" .. key .. "'") end
      bound[i] = defaults and defaults[i]
    end
  end
  return bound
end

local Parser = {}
Parser.__index = Parser

function Parser:fail(message, position)
  self.raise(message, position or self.i - 1)
end

function Parser:peek()
  local cp = self.cps[self.i]
  return cp and cp < 128 and string.char(cp) or (cp and "<unicode>" or "")
end

function Parser:skip(flags)
  if flags & VERBOSE == 0 then return end
  while self.i <= #self.cps do
    if VERBOSE_SPACE[self.cps[self.i]] then self.i = self.i + 1
    elseif self.cps[self.i] == 35 then
      repeat self.i = self.i + 1 until self.i > #self.cps or self.cps[self.i] == 10
    else break end
  end
end

function Parser:name(terminator)
  local out = {}
  while self.i <= #self.cps and self:peek() ~= terminator do
    local cp = self.cps[self.i]
    if cp >= 128 then throw("NotImplementedError", "non-ASCII regular expression group names") end
    out[#out + 1] = string.char(cp)
    self.i = self.i + 1
  end
  if self:peek() ~= terminator then self:fail("missing " .. terminator .. ", unterminated name") end
  self.i = self.i + 1
  local name = table.concat(out)
  if not name:match("^[A-Za-z_][A-Za-z_0-9]*$") then self:fail("bad character in group name '" .. name .. "'") end
  return name
end

function Parser:reference(id, flags)
  if id == nil or id < 1 or id > self.groups then self:fail("invalid group reference") end
  if self.open[id] then self:fail("cannot refer to an open group") end
  if self.behind_base and id > self.behind_base then self:fail("cannot refer to group defined in the same lookbehind subpattern") end
  return { op = "reference", id = id, flags = flags, width = self.widths[id] }
end

function Parser:escape(flags, in_class)
  local ch, cp = self:peek(), self.cps[self.i]
  if cp == nil then self:fail("bad escape (end of pattern)") end
  self.i = self.i + 1
  if ch:match("^[dDsSwW]$") then return { op = "category", name = ch, flags = flags } end
  if not in_class and (ch == "A" or ch == "Z" or ch == "b" or ch == "B") then
    return { op = "anchor", name = ch, flags = flags }
  end
  if ESCAPES[ch] then return { op = "literal", cp = ESCAPES[ch], flags = flags } end
  if ch == "x" or ch == "u" or ch == "U" then
    if self.binary and ch ~= "x" then self:fail("bad escape \\" .. ch) end
    local size = ch == "x" and 2 or (ch == "u" and 4 or 8)
    local value = 0
    for _ = 1, size do
      local digit = self:peek()
      if not digit:match("^[0-9a-fA-F]$") then self:fail("incomplete escape \\" .. ch) end
      value = value * 16 + tonumber(digit, 16)
      self.i = self.i + 1
    end
    if value > 0x10ffff then self:fail("bad Unicode escape") end
    return { op = "literal", cp = value, flags = flags }
  end
  if ch == "N" and not self.binary then throw("NotImplementedError", "Unicode character-name regex escapes") end
  if ch:match("^[0-9]$") then
    local digits = ch
    if ch == "0" or in_class then
      if ch == "8" or ch == "9" then self:fail("bad escape \\" .. ch) end
      for _ = 1, 2 do
        if not self:peek():match("^[0-7]$") then break end
        digits, self.i = digits .. self:peek(), self.i + 1
      end
      local value = tonumber(digits, 8)
      if value > 255 then self:fail("octal escape outside of range 0-0o377") end
      return { op = "literal", cp = value, flags = flags }
    end
    if self:peek():match("^[0-9]$") then
      digits, self.i = digits .. self:peek(), self.i + 1
      if digits:match("^[0-7][0-7]$") and self:peek():match("^[0-7]$") then
        digits, self.i = digits .. self:peek(), self.i + 1
        local value = tonumber(digits, 8)
        if value > 255 then self:fail("octal escape outside of range 0-0o377") end
        return { op = "literal", cp = value, flags = flags }
      end
    end
    return self:reference(tonumber(digits), flags)
  end
  if ch:match("^[A-Za-z]$") then self:fail("bad escape \\" .. ch) end
  return { op = "literal", cp = cp, flags = flags }
end

function Parser:class(flags)
  local negate = self:peek() == "^"
  if negate then self.i = self.i + 1 end
  local items = {}
  local function atom()
    local cp = self.cps[self.i]
    self.i = self.i + 1
    if cp == 92 then return self:escape(flags, true) end
    return { op = "literal", cp = cp }
  end
  while self.i <= #self.cps do
    if self:peek() == "]" and #items > 0 then
      self.i = self.i + 1
      return { op = "class", items = items, negate = negate, flags = flags }
    end
    local first = atom()
    if self:peek() == "-" and self.cps[self.i + 1] ~= 93 and self.cps[self.i + 1] ~= nil then
      self.i = self.i + 1
      local last = atom()
      if first.op ~= "literal" or last.op ~= "literal" or first.cp > last.cp then self:fail("bad character range") end
      items[#items + 1] = { op = "range", lo = first.cp, hi = last.cp }
    elseif first.op == "literal" then
      items[#items + 1] = { op = "range", lo = first.cp, hi = first.cp }
    else items[#items + 1] = first end
  end
  self:fail("unterminated character set")
end

local function fixed_width(node)
  local op = node.op
  if op == "literal" or op == "class" or op == "category" or op == "dot" then return 1 end
  if op == "anchor" or op == "assert" then return 0 end
  if op == "reference" then return node.width end
  if op == "group" or op == "atomic" then return fixed_width(node.child) end
  if op == "repeat" then
    local width = fixed_width(node.child)
    if width == 0 then return 0 end
    if width and node.min == node.max then return width * node.min end
    return nil
  end
  if op == "sequence" then
    local total = 0
    for _, child in ipairs(node.items) do
      local width = fixed_width(child)
      if width == nil then return nil end
      total = total + width
    end
    return total
  end
  if op == "alternate" or op == "conditional" then
    local expected = fixed_width(node.items[1])
    for i = 2, #node.items do
      if fixed_width(node.items[i]) ~= expected then return nil end
    end
    return expected
  end
end

function Parser:flag_group(flags, top, empty)
  local add, remove, minus = 0, 0, false
  while true do
    local ch = self:peek()
    if ch == "-" and not minus then minus, self.i = true, self.i + 1
    elseif FLAG_BITS[ch] then
      local bit = FLAG_BITS[ch]
      if minus then remove = remove | bit else add = add | bit end
      self.i = self.i + 1
    else break end
  end
  if add & remove ~= 0 then self:fail("flag turned on and off") end
  if remove & (ASCII | UNICODE | LOCALE) ~= 0 then self:fail("cannot turn off flags 'a', 'u' and 'L'") end
  if add & ASCII ~= 0 and add & (UNICODE | LOCALE) ~= 0
    or add & UNICODE ~= 0 and add & LOCALE ~= 0 then self:fail("flags 'a', 'u' and 'L' are incompatible") end
  if self.binary and add & UNICODE ~= 0 then self:fail("cannot use 'u' flag with a bytes pattern") end
  if not self.binary and add & LOCALE ~= 0 then self:fail("cannot use 'L' flag with a str pattern") end
  if add & LOCALE ~= 0 then throw("NotImplementedError", "locale-dependent regular expressions") end
  if add & (ASCII | UNICODE) ~= 0 then flags = flags & ~(ASCII | UNICODE) end
  flags = (flags | add) & ~remove
  if self:peek() == ")" and not minus then
    if not top or not empty then self:fail("global flags not at the start of the expression") end
    self.i, self.flags = self.i + 1, flags
    return nil, flags
  end
  if self:peek() ~= ":" or (minus and remove == 0) then self:fail("missing flag or ':'") end
  self.i = self.i + 1
  local child = self:expression(flags, false)
  if self:peek() ~= ")" then self:fail("missing ), unterminated subpattern") end
  self.i = self.i + 1
  return child
end

function Parser:group(flags, top, empty)
  local id, name, op, negative, behind = nil, nil, "group", false, false
  if self:peek() == "?" then
    self.i = self.i + 1
    local extension = self:peek()
    self.i = self.i + 1
    if extension == ":" then op = "noncapture"
    elseif extension == "=" or extension == "!" then op, negative = "assert", extension == "!"
    elseif extension == ">" then op = "atomic"
    elseif extension == "<" then
      local kind = self:peek()
      if kind ~= "=" and kind ~= "!" then self:fail("unknown extension ?<") end
      self.i, op, negative, behind = self.i + 1, "assert", kind == "!", true
    elseif extension == "P" then
      if self:peek() == "=" then
        self.i = self.i + 1
        local ref = self:name(")")
        if self.names[ref] == nil then self:fail("unknown group name '" .. ref .. "'") end
        return self:reference(self.names[ref], flags)
      end
      if self:peek() ~= "<" then self:fail("unknown extension ?P") end
      self.i = self.i + 1
      name = self:name(">")
      if self.names[name] then self:fail("redefinition of group name '" .. name .. "'") end
    elseif extension == "#" then
      while self.i <= #self.cps and self:peek() ~= ")" do
        if self:peek() == "\\" then self.i = self.i + 1 end
        self.i = self.i + 1
      end
      if self:peek() ~= ")" then self:fail("missing ), unterminated comment") end
      self.i = self.i + 1
      return nil, flags
    elseif extension == "(" then
      local reference
      if self:peek():match("^[0-9]$") then
        local digits = ""
        while self:peek():match("^[0-9]$") do digits, self.i = digits .. self:peek(), self.i + 1 end
        if self:peek() ~= ")" then self:fail("bad group number") end
        self.i, reference = self.i + 1, tonumber(digits)
        self.conditionals[#self.conditionals + 1] = reference
      else
        local ref = self:name(")")
        reference = self.names[ref]
        if not reference then self:fail("unknown group name '" .. ref .. "'") end
      end
      local child = self:expression(flags, false)
      local items = child.op == "alternate" and child.items or { child }
      if #items > 2 then self:fail("conditional backref with more than two branches") end
      if #items == 1 then items[2] = { op = "sequence", items = {} } end
      if self:peek() ~= ")" then self:fail("missing ), unterminated subpattern") end
      self.i = self.i + 1
      return { op = "conditional", id = reference, items = items }
    elseif FLAG_BITS[extension] or extension == "-" then
      self.i = self.i - 1
      return self:flag_group(flags, top, empty)
    else self:fail("unknown extension ?" .. extension) end
  end
  if op == "group" then
    self.groups = self.groups + 1
    id, self.open[self.groups] = self.groups, true
    if name then self.names[name], self.reverse_names[id] = id, name end
  end
  local old_behind = self.behind_base
  if behind and old_behind == nil then self.behind_base = self.groups end
  local child = self:expression(flags, false)
  self.behind_base = old_behind
  if self:peek() ~= ")" then self:fail("missing ), unterminated subpattern") end
  self.i = self.i + 1
  if id then self.open[id], self.widths[id] = nil, fixed_width(child) end
  if op == "noncapture" then return child end
  local width = behind and fixed_width(child) or nil
  if behind and width == nil then self:fail("look-behind requires fixed-width pattern") end
  return { op = op, child = child, id = id, negative = negative, behind = width }
end

function Parser:quantify(atom, flags)
  self:skip(flags)
  local ch, min, max = self:peek()
  if ch == "*" then min, max = 0, math.huge
  elseif ch == "+" then min, max = 1, math.huge
  elseif ch == "?" then min, max = 0, 1
  elseif ch == "{" then
    local saved, lower, upper = self.i, "", ""
    self.i = self.i + 1
    while self:peek():match("^[0-9]$") do lower, self.i = lower .. self:peek(), self.i + 1 end
    if self:peek() == "," then
      self.i = self.i + 1
      while self:peek():match("^[0-9]$") do upper, self.i = upper .. self:peek(), self.i + 1 end
      min, max = tonumber(lower) or 0, tonumber(upper) or math.huge
    elseif lower ~= "" then min, max = tonumber(lower), tonumber(lower) end
    if self:peek() ~= "}" or min == nil then self.i = saved; return atom end
    if min >= 0xffffffff or max ~= math.huge and max >= 0xffffffff then throw("OverflowError", "the repetition number is too large") end
    if min > max then self:fail("min repeat greater than max repeat") end
  else return atom end
  if atom.op == "anchor" then self:fail("nothing to repeat") end
  self.i = self.i + 1
  local lazy, possessive = self:peek() == "?", self:peek() == "+"
  if lazy or possessive then self.i = self.i + 1 end
  local node = { op = "repeat", child = atom, min = min, max = max, lazy = lazy }
  if possessive then node = { op = "atomic", child = node } end
  return node
end

function Parser:expression(flags, top)
  local branches, items = {}, {}
  while true do
    self.I:fuel()
    self:skip(flags)
    local cp, ch = self.cps[self.i], self:peek()
    if cp == nil or ch == ")" then break end
    self.i = self.i + 1
    if ch == "|" then
      branches[#branches + 1] = { op = "sequence", items = items }
      items = {}
    else
      local atom, newflags
      if ch == "(" then atom, newflags = self:group(flags, top, #branches == 0 and #items == 0)
      elseif ch == "[" then atom = self:class(flags)
      elseif ch == "\\" then atom = self:escape(flags, false)
      elseif ch == "." then atom = { op = "dot", flags = flags }
      elseif ch == "^" or ch == "$" then atom = { op = "anchor", name = ch, flags = flags }
      elseif ch == "*" or ch == "+" or ch == "?" then self:fail("nothing to repeat")
      elseif ch == "{" then
        self.i = self.i - 1
        self:quantify({ op = "anchor" }, flags)
        self.i = self.i + 1
        atom = { op = "literal", cp = cp, flags = flags }
      else atom = { op = "literal", cp = cp, flags = flags } end
      if newflags then flags = newflags end
      if atom then items[#items + 1] = self:quantify(atom, flags) end
    end
  end
  branches[#branches + 1] = { op = "sequence", items = items }
  if #branches == 1 then return branches[1] end
  return { op = "alternate", items = branches }
end

local function compile_code(root, groups)
  local next_slot = groups * 2 + 1
  local emit
  emit = function(node, continuation)
    local op = node.op
    if op == "sequence" then
      for i = #node.items, 1, -1 do continuation = emit(node.items[i], continuation) end
      return continuation
    end
    if op == "alternate" then
      local branch = emit(node.items[#node.items], continuation)
      for i = #node.items - 1, 1, -1 do
        branch = { op = "split", first = emit(node.items[i], continuation), second = branch }
      end
      return branch
    end
    if op == "group" then
      local close = { op = "save", slot = node.id * 2, id = node.id, next = continuation }
      return { op = "save", slot = node.id * 2 - 1, next = emit(node.child, close) }
    end
    if op == "repeat" then
      local slot = next_slot
      next_slot = next_slot + 3
      local decision = { op = "repeat", slot = slot, min = node.min, max = node.max,
        lazy = node.lazy, next = continuation }
      local finish = { op = "repeat_end", slot = slot, next = decision }
      decision.child = { op = "repeat_start", slot = slot, next = emit(node.child, finish) }
      return { op = "repeat_init", slot = slot, next = decision }
    end
    if op == "assert" or op == "atomic" then
      return { op = op, child = emit(node.child, { op = "accept" }),
        negative = node.negative, behind = node.behind, next = continuation }
    end
    if op == "conditional" then
      return { op = op, id = node.id, first = emit(node.items[1], continuation),
        second = emit(node.items[2], continuation) }
    end
    node.next = continuation
    return node
  end
  return emit(root, { op = "accept" })
end

local function anchor(node, ctx, pos)
  local name, cps, stop = node.name, ctx.cps, ctx.stop
  if name == "A" then return pos == 0 end
  if name == "Z" then return pos == stop end
  if name == "^" then return pos == 0 or node.flags & MULTILINE ~= 0 and cps[pos] == 10 end
  if name == "$" then
    return pos == stop or cps[pos + 1] == 10 and (pos == stop - 1 or node.flags & MULTILINE ~= 0)
  end
  local left = pos > 0 and category(cps[pos], "w", node.flags, ctx.binary)
  local right = pos < stop and category(cps[pos + 1], "w", node.flags, ctx.binary)
  if name == "b" then return left ~= right end
  -- CPython 3.12 does not match \B against an empty subject region.
  return stop > 0 and left == right
end

local run
run = function(code, ctx, start, initial, end_required, no_empty)
  local regs, history, choices = {}, {}, {}
  if initial then for slot, value in pairs(initial) do regs[slot] = value end end
  local pc, pos = code, start
  local function set(slot, value)
    if regs[slot] == value then return end
    history[#history + 1] = { slot, regs[slot] }
    regs[slot] = value
  end
  local function choice(next_pc)
    choices[#choices + 1] = { next_pc, pos, #history }
  end
  local function restore()
    local frame = choices[#choices]
    if frame == nil then return false end
    choices[#choices] = nil
    for i = #history, frame[3] + 1, -1 do
      local entry = history[i]
      regs[entry[1]], history[i] = entry[2], nil
    end
    pc, pos = frame[1], frame[2]
    return true
  end
  while true do
    ctx.I:fuel()
    local op, fail = pc.op, false
    if op == "accept" then
      if (end_required == nil or pos == end_required) and not (no_empty and pos == start) then return pos, regs end
      fail = true
    elseif op == "split" then choice(pc.second); pc = pc.first
    elseif op == "save" then
      set(pc.slot, pos)
      if pc.id then set(0, pc.id) end
      pc = pc.next
    elseif op == "repeat_init" then
      set(pc.slot, 0); set(pc.slot + 2, false); pc = pc.next
    elseif op == "repeat_start" then set(pc.slot + 1, pos); pc = pc.next
    elseif op == "repeat_end" then
      set(pc.slot, regs[pc.slot] + 1)
      set(pc.slot + 2, pos == regs[pc.slot + 1])
      pc = pc.next
    elseif op == "repeat" then
      local count = regs[pc.slot]
      if count >= pc.max or count >= pc.min and regs[pc.slot + 2] then pc = pc.next
      elseif count < pc.min then pc = pc.child
      elseif pc.lazy then choice(pc.child); pc = pc.next
      else choice(pc.next); pc = pc.child end
    elseif op == "conditional" then
      pc = regs[pc.id * 2] ~= nil and pc.first or pc.second
    elseif op == "anchor" then
      if anchor(pc, ctx, pos) then pc = pc.next else fail = true end
    elseif op == "assert" or op == "atomic" then
      local beginning = pos - (pc.behind or 0)
      local finish, captured
      if beginning >= 0 then
        finish, captured = run(pc.child, ctx, beginning, regs, pc.behind and pos or nil)
      end
      if pc.negative then
        if finish ~= nil then fail = true else pc = pc.next end
      elseif finish == nil then fail = true
      else
        for slot = 0, ctx.groups * 2 do set(slot, captured[slot]) end
        if op == "atomic" then pos = finish end
        pc = pc.next
      end
    elseif op == "reference" then
      local first, last = regs[pc.id * 2 - 1], regs[pc.id * 2]
      if first == nil or last == nil or pos + last - first > ctx.stop then fail = true
      else
        for offset = 1, last - first do
          ctx.I:fuel()
          if not equal_cp(ctx.cps[first + offset], ctx.cps[pos + offset], pc.flags, ctx.binary) then fail = true; break end
        end
        if not fail then pos, pc = pos + last - first, pc.next end
      end
    elseif pos >= ctx.stop then fail = true
    else
      local cp, matched = ctx.cps[pos + 1]
      if op == "literal" then matched = equal_cp(cp, pc.cp, pc.flags, ctx.binary)
      elseif op == "dot" then matched = cp ~= 10 or pc.flags & DOTALL ~= 0
      elseif op == "category" then matched = category(cp, pc.name, pc.flags, ctx.binary)
      elseif op == "class" then matched = character_class(pc, cp, ctx.binary) end
      if matched then pos, pc = pos + 1, pc.next else fail = true end
    end
    if fail and not restore() then return nil end
  end
end

local function context(I, pattern, string, pos, endpos)
  local data, binary = string_data(string, "string")
  if binary ~= pattern.binary then
    throw("TypeError", binary and "cannot use a string pattern on a bytes-like object"
      or "cannot use a bytes pattern on a string-like object")
  end
  local cps, offsets = units(data, binary)
  pos = math.min(#cps, math.max(0, integer(pos or 0, "pos")))
  endpos = endpos == nil and #cps or math.min(#cps, math.max(0, integer(endpos, "endpos")))
  return { I = I, data = data, string = string, binary = binary, cps = cps,
    offsets = offsets, pos = pos, stop = endpos, groups = pattern.props.groups }
end

local function slice(ctx, start, stop)
  return text_value(ctx.data:sub(ctx.offsets[start + 1], ctx.offsets[stop + 1] - 1), ctx.binary)
end

local function raw_slice(ctx, start, stop)
  return ctx.data:sub(ctx.offsets[start + 1], ctx.offsets[stop + 1] - 1)
end

local function capture(match, id, default)
  if id == 0 then return slice(match.ctx, match.first, match.last) end
  local start, stop = match.regs[id * 2 - 1], match.regs[id * 2]
  if start == nil or stop == nil then return default end
  return slice(match.ctx, start, stop)
end

local function group_id(match, value)
  local id
  if type(value) == "string" then id = match.pattern.names[value]
  else
    id = V.as_index(value)
    if id ~= nil then id = V.clamp_index(id, -1, match.pattern.props.groups + 1) end
  end
  if id == nil or id < 0 or id > match.pattern.props.groups then throw("IndexError", "no such group") end
  return id
end

local function replacement(pattern, value)
  local data, binary = string_data(value, "replacement")
  if binary ~= pattern.binary then throw("TypeError", "replacement and pattern must have the same type") end
  local cps = units(data, binary)
  local pieces, literal, i = {}, {}, 1
  local function append(cp)
    literal[#literal + 1] = binary and string.char(cp) or utf8.char(cp)
  end
  local function flush()
    if #literal > 0 then pieces[#pieces + 1] = table.concat(literal); literal = {} end
  end
  local function ref(id)
    if id == nil or id < 0 or id > pattern.props.groups then pattern.raise("invalid group reference", i - 1, value) end
    flush()
    pieces[#pieces + 1] = id
  end
  local function ascii(index)
    local cp = cps[index]
    return cp and cp < 128 and string.char(cp) or ""
  end
  while i <= #cps do
    local cp = cps[i]
    i = i + 1
    if cp ~= 92 then append(cp)
    else
      local ch = ascii(i)
      cp, i = cps[i], i + 1
      if cp == nil then pattern.raise("bad escape (end of pattern)", i - 2, value) end
      if ch == "g" then
        if ascii(i) ~= "<" then pattern.raise("missing <", i - 1, value) end
        i = i + 1
        local name = {}
        while cps[i] and ascii(i) ~= ">" do
          name[#name + 1] = binary and string.char(cps[i]) or utf8.char(cps[i])
          i = i + 1
        end
        if ascii(i) ~= ">" then pattern.raise("missing >, unterminated name", i - 1, value) end
        i = i + 1
        name = table.concat(name)
        if name:match("^[0-9]+$") then ref(tonumber(name))
        else
          if name:find("[\128-\255]") then throw("NotImplementedError", "non-ASCII regular expression group names") end
          if not name:match("^[A-Za-z_][A-Za-z_0-9]*$") then pattern.raise("bad character in group name", i - 1, value) end
          local id = pattern.names[name]
          if id == nil then throw("IndexError", "unknown group name '" .. name .. "'") end
          ref(id)
        end
      elseif ch == "0" then
        local digits = ch
        for _ = 1, 2 do
          if not ascii(i):match("^[0-7]$") then break end
          digits, i = digits .. ascii(i), i + 1
        end
        append(tonumber(digits, 8))
      elseif ch:match("^[1-9]$") then
        local digits = ch
        if ascii(i):match("^[0-9]$") then digits, i = digits .. ascii(i), i + 1 end
        if #digits == 2 and digits:match("^[0-7][0-7]$") and ascii(i):match("^[0-7]$") then
          digits, i = digits .. ascii(i), i + 1
          local octal = tonumber(digits, 8)
          if octal > 255 then pattern.raise("octal escape outside of range 0-0o377", i - 1, value) end
          append(octal)
        else ref(tonumber(digits)) end
      elseif ESCAPES[ch] then append(ESCAPES[ch])
      elseif ch == "\\" then append(92)
      elseif ch:match("^[A-Za-z]$") then pattern.raise("bad escape \\" .. ch, i - 2, value)
      else append(92); append(cp) end
    end
  end
  flush()
  return pieces
end

local function expand(match, pieces)
  local out = {}
  for _, piece in ipairs(pieces) do
    if type(piece) == "number" then
      local captured = capture(match, piece, NONE)
      if captured == NONE then out[#out + 1] = ""
      elseif match.ctx.binary then out[#out + 1] = captured.b
      else out[#out + 1] = captured end
    else out[#out + 1] = piece end
  end
  return table.concat(out)
end

local function make_match(pattern, ctx, start, finish, regs)
  local match = { kind = "nativeobject", nkind = "re.Match", pytype = pattern.match_type,
    pattern = pattern, ctx = ctx, first = start, last = finish, regs = regs, methods = {} }
  local lastindex = regs[0]
  local spans = { V.tuple({ start, finish }) }
  for id = 1, pattern.props.groups do
    spans[#spans + 1] = V.tuple({ regs[id * 2 - 1] or -1, regs[id * 2] or -1 })
  end
  match.props = { re = pattern, string = ctx.string, pos = ctx.pos, endpos = ctx.stop,
    lastindex = lastindex or NONE,
    lastgroup = lastindex and pattern.reverse_names[lastindex] or NONE, regs = V.tuple(spans) }
  match.methods.group = bi("group", function(_I, args, kw)
    H.no_kw("group", kw)
    if #args == 0 then return capture(match, 0, NONE) end
    if #args == 1 then return capture(match, group_id(match, args[1]), NONE) end
    local out = {}
    for i, value in ipairs(args) do out[i] = capture(match, group_id(match, value), NONE) end
    return V.tuple(out)
  end)
  match.methods.groups = bi("groups", function(_I, args, kw)
    local a = arguments("groups", args, kw, { "default" }, 0, { NONE })
    local out = {}
    for id = 1, pattern.props.groups do out[id] = capture(match, id, a[1]) end
    return V.tuple(out)
  end)
  match.methods.groupdict = bi("groupdict", function(_I, args, kw)
    local a = arguments("groupdict", args, kw, { "default" }, 0, { NONE })
    local out = V.new_dict()
    for id = 1, pattern.props.groups do
      local name = pattern.reverse_names[id]
      if name then V.dict_set(out, name, capture(match, id, a[1])) end
    end
    return out
  end)
  for _, name in ipairs({ "span", "start", "end" }) do
    match.methods[name] = bi(name, function(_I, args, kw)
      H.no_kw(name, kw); H.arg_count(name, args, 0, 1)
      local id = group_id(match, args[1] or 0)
      local first, last
      if id == 0 then first, last = start, finish
      else first, last = regs[id * 2 - 1] or -1, regs[id * 2] or -1 end
      if name == "start" then return first end
      if name == "end" then return last end
      return V.tuple({ first, last })
    end)
  end
  match.methods.expand = bi("expand", function(_I, args, kw)
    local a = arguments("expand", args, kw, { "template" }, 1)
    return text_value(expand(match, replacement(pattern, a[1])), ctx.binary)
  end)
  -- Native-object indexing dispatch can call this same bound builtin.
  match.methods.__getitem__ = match.methods.group
  return match
end

local function search(pattern, ctx, start, anchored, full, no_empty)
  if start > ctx.stop then return NONE end
  local last = anchored and start or ctx.stop
  for position = start, last do
    local finish, regs = run(pattern.code, ctx, position, nil,
      full and ctx.stop or nil, no_empty and position == start)
    if finish ~= nil then return make_match(pattern, ctx, position, finish, regs) end
  end
  return NONE
end

local function match_iterator(pattern, ctx)
  local position, no_empty, done = ctx.pos, false, false
  return { kind = "iter", iname = "callable_iterator", retval = NONE, next = function()
    if done then return NONE, false end
    local match = search(pattern, ctx, position, false, false, no_empty)
    if match == NONE then done = true; return NONE, false end
    position, no_empty = match.last, match.last == match.first
    return match, true
  end }
end

local function pattern_methods(pattern)
  local methods = {}
  for _, name in ipairs({ "match", "search", "fullmatch", "findall", "finditer" }) do
    methods[name] = bi(name, function(I, args, kw)
      local a = arguments(name, args, kw, { "string", "pos", "endpos" }, 1, { [2] = 0 })
      local ctx = context(I, pattern, a[1], a[2], a[3])
      if name == "match" or name == "search" or name == "fullmatch" then
        return search(pattern, ctx, ctx.pos, name ~= "search", name == "fullmatch", false)
      end
      local it = match_iterator(pattern, ctx)
      if name == "finditer" then return it end
      local out, count = {}, pattern.props.groups
      local empty = text_value("", ctx.binary)
      while true do
        local match, more = it.next()
        if not more then break end
        if count == 0 then out[#out + 1] = capture(match, 0, empty)
        elseif count == 1 then out[#out + 1] = capture(match, 1, empty)
        else
          local groups = {}
          for id = 1, count do groups[id] = capture(match, id, empty) end
          out[#out + 1] = V.tuple(groups)
        end
      end
      return V.list(out)
    end)
  end
  methods.split = bi("split", function(I, args, kw)
    local a = arguments("split", args, kw, { "string", "maxsplit" }, 1, { [2] = 0 })
    local limit = integer(a[2], "maxsplit")
    local ctx = context(I, pattern, a[1])
    local it, out, previous, count = match_iterator(pattern, ctx), {}, 0, 0
    while limit == 0 or count < limit do
      local match, more = it.next()
      if not more then break end
      out[#out + 1] = slice(ctx, previous, match.first)
      for id = 1, pattern.props.groups do out[#out + 1] = capture(match, id, NONE) end
      previous, count = match.last, count + 1
    end
    out[#out + 1] = slice(ctx, previous, #ctx.cps)
    return V.list(out)
  end)
  for _, name in ipairs({ "sub", "subn" }) do
    methods[name] = bi(name, function(I, args, kw)
      local a = arguments(name, args, kw, { "repl", "string", "count" }, 2, { [3] = 0 })
      local limit = integer(a[3], "count")
      local ctx = context(I, pattern, a[2])
      local repl = a[1]
      local is_template = type(repl) == "string" or type(repl) == "table" and repl.kind == "bytes"
      local pieces
      if is_template then pieces = replacement(pattern, repl)
      elseif type(repl) ~= "table" or not (repl.kind == "function" or repl.kind == "builtin"
        or repl.kind == "boundmethod" or repl.kind == "instance" or repl.kind == "class" or repl.kind == "btype") then
        throw("TypeError", "replacement must be a string or callable")
      end
      local it, out, previous, count = match_iterator(pattern, ctx), {}, 0, 0
      while limit == 0 or count < limit do
        local match, more = it.next()
        if not more then break end
        out[#out + 1] = raw_slice(ctx, previous, match.first)
        if pieces then out[#out + 1] = expand(match, pieces)
        else
          local result = I:call(repl, { match }, {})
          if result ~= NONE then
            local data, binary = string_data(result, "replacement callback result")
            if binary ~= ctx.binary then throw("TypeError", "replacement callback result has the wrong string type") end
            out[#out + 1] = data
          end
        end
        previous, count = match.last, count + 1
      end
      out[#out + 1] = raw_slice(ctx, previous, #ctx.cps)
      local result = text_value(table.concat(out), ctx.binary)
      if name == "subn" then return V.tuple({ result, count }) end
      return result
    end)
  end
  return methods
end

--- Construct the native re module using the interpreter's callback and fuel hooks.
-- Pattern and Match methods are bound values.builtin closures; properties use
-- nativeobject.props. finditer returns the runtime's ordinary iterator protocol.
function M.make_module(I)
  local Error = V.new_class("error", { V.EXC_CLASSES.Exception }, { __module__ = "re" })
  local function regex_error(message, pattern, position)
    local inst = V.new_instance(Error)
    inst.d.msg, inst.d.pattern, inst.d.pos = message, pattern or NONE, position or NONE
    inst.d.lineno, inst.d.colno = NONE, NONE
    if pattern ~= nil and position ~= nil then
      local data, binary = string_data(pattern, "pattern")
      local cps = units(data, binary)
      local line, column = 1, 1
      for j = 1, math.min(position, #cps) do
        if cps[j] == 10 then line, column = line + 1, 1 else column = column + 1 end
      end
      inst.d.lineno, inst.d.colno = line, column
      message = message .. " at position " .. position
      if line > 1 then message = message .. " (line " .. line .. ", column " .. column .. ")" end
    end
    inst.d.args = V.tuple({ message })
    V.throw_val(inst)
  end
  local Pattern = V.btype("re.Pattern", function() throw("TypeError", "cannot create 're.Pattern' instances") end)
  local Match = V.btype("re.Match", function() throw("TypeError", "cannot create 're.Match' instances") end)
  local function compile(value, supplied_flags)
    local flags = integer(supplied_flags or 0, "flags")
    if flags < -0x80000000 or flags > 0x7fffffff then
      throw("OverflowError", "Python int too large to convert to C int")
    end
    if type(value) == "table" and value.pytype == Pattern then
      if flags ~= 0 then throw("ValueError", "cannot process flags argument with a compiled pattern") end
      return value
    end
    local data, binary = string_data(value, "first argument")
    if flags & ~(IGNORECASE | LOCALE | MULTILINE | DOTALL | UNICODE | VERBOSE | ASCII) ~= 0 then
      throw("NotImplementedError", "unsupported regular expression flags (including TEMPLATE and DEBUG)")
    end
    if binary and flags & UNICODE ~= 0 then throw("ValueError", "cannot use UNICODE flag with a bytes pattern") end
    if not binary and flags & LOCALE ~= 0 then throw("ValueError", "cannot use LOCALE flag with a str pattern") end
    if flags & ASCII ~= 0 and flags & UNICODE ~= 0 then throw("ValueError", "ASCII and UNICODE flags are incompatible") end
    if flags & ASCII ~= 0 and flags & LOCALE ~= 0 then throw("ValueError", "ASCII and LOCALE flags are incompatible") end
    if flags & LOCALE ~= 0 then throw("NotImplementedError", "locale-dependent regular expressions") end
    if not binary and flags & ASCII == 0 then flags = flags | UNICODE end
    local function raise(message, position, source) regex_error(message, source or value, position) end
    local parser = setmetatable({ I = I, cps = units(data, binary), binary = binary,
      i = 1, flags = flags, groups = 0, names = {}, reverse_names = {}, open = {},
      widths = {}, conditionals = {}, raise = raise }, Parser)
    local root = parser:expression(flags, true)
    if parser.i <= #parser.cps then parser:fail("unbalanced parenthesis") end
    for _, id in ipairs(parser.conditionals) do
      if id < 1 or id > parser.groups then parser:fail("invalid group reference " .. id) end
    end
    local names = V.new_dict()
    for id = 1, parser.groups do
      local name = parser.reverse_names[id]
      if name then V.dict_set(names, name, id) end
    end
    local pattern = { kind = "nativeobject", nkind = "re.Pattern", pytype = Pattern,
      match_type = Match, binary = binary, names = parser.names, reverse_names = parser.reverse_names,
      code = compile_code(root, parser.groups), raise = raise,
      props = { pattern = value, flags = parser.flags, groups = parser.groups, groupindex = names } }
    pattern.methods = pattern_methods(pattern)
    return pattern
  end
  local ns = { Pattern = Pattern, Match = Match, error = Error,
    NOFLAG = 0, TEMPLATE = 1, T = 1, IGNORECASE = IGNORECASE, I = IGNORECASE,
    LOCALE = LOCALE, L = LOCALE, MULTILINE = MULTILINE, M = MULTILINE,
    DOTALL = DOTALL, S = DOTALL, UNICODE = UNICODE, U = UNICODE,
    VERBOSE = VERBOSE, X = VERBOSE, DEBUG = 128, ASCII = ASCII, A = ASCII }
  ns.compile = bi("compile", function(_I, args, kw)
    local a = arguments("compile", args, kw, { "pattern", "flags" }, 1, { [2] = 0 })
    return compile(a[1], a[2])
  end)
  for _, name in ipairs({ "match", "search", "fullmatch", "findall", "finditer", "split", "sub", "subn" }) do
    ns[name] = bi(name, function(call_I, args, kw)
      local names, defaults, required
      if name == "sub" or name == "subn" then
        names, defaults, required = { "pattern", "repl", "string", "count", "flags" }, { [4] = 0, [5] = 0 }, 3
      elseif name == "split" then
        names, defaults, required = { "pattern", "string", "maxsplit", "flags" }, { [3] = 0, [4] = 0 }, 2
      else names, defaults, required = { "pattern", "string", "flags" }, { [3] = 0 }, 2 end
      local a = arguments(name, args, kw, names, required, defaults)
      local pattern = compile(a[1], a[#names])
      local call_args = {}
      for j = 2, #names - 1 do call_args[#call_args + 1] = a[j] end
      return pattern.methods[name].fn(call_I, call_args, {})
    end)
  end
  ns.escape = bi("escape", function(_I, args, kw)
    local a = arguments("escape", args, kw, { "pattern" }, 1)
    local data, binary = string_data(a[1], "pattern")
    local escaped = data:gsub("[%(%)%[%]{}%?%*%+%-%|%^%$\\%.&~# \t\n\r\v\f]", "\\%0")
    return text_value(escaped, binary)
  end)
  -- This implementation has no compiled-pattern cache to retain or clear.
  ns.purge = bi("purge", function(_I, args, kw)
    H.arg_count("purge", args, 0, 0); H.no_kw("purge", kw)
    return NONE
  end)
  return { kind = "nativemodule", name = "re", ns = ns }
end

return M
