#!/usr/bin/env python3
"""Extract portable Unicode 15.0.0 tables with CPython 3.12.12.

Run with the pinned interpreter, optionally passing --ucd DIRECTORY containing
NameAliases.txt and NamedSequences.txt from Unicode 15.0.0. Without --ucd, those
two integrity-checked source files are downloaded from unicode.org. Properties,
names, decompositions, and composition exclusions come from host unicodedata.
The Python modules contain packed ASCII constants decoded lazily by unicodedata.
The Lua and Go identifier helpers use compact Unicode 15.0.0 XID ranges
extracted from the pinned interpreter's str.isidentifier implementation. The
Lua and TypeScript helpers also contain pinned printable character ranges.
Use --identifiers-only to regenerate just those native helpers.
"""

import argparse
import hashlib
import sys
import unicodedata as ucd
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DESTINATION = ROOT / "src/diaspore/stdlib"
SOURCES = {
    "NameAliases.txt": "3e39509e8fae3e5d50ba73759d0b97194501d14a9c63107a6372a46b38be18e8",
    "NamedSequences.txt": "1d5202155f14841973aa540b1625f4befbde185ac77ce5aceaaaa0501a68bd66",
}
HEADER = '''"""Unicode 15.0.0 data generated by tools/generate_unicode.py.

Source: CPython 3.12.12 unicodedata; Unicode Character Database 15.0.0.
Copyright Unicode, Inc. See https://www.unicode.org/terms_of_use.html.
Do not edit by hand. ASCII hex integers are space-separated; sorted keys use
deltas. Records use newline-separated, tab-delimited fields. Names store the
hex common-prefix length, a colon, and the remaining suffix on each line.
unicodedata decodes each table group only when first needed, without codecs.
"""
'''


def source_records(filename, directory):
    """Read the pinned alias or named-sequence records."""
    if directory is None:
        url = "https://www.unicode.org/Public/15.0.0/ucd/" + filename
        with urllib.request.urlopen(url) as response:
            data = response.read()
    else:
        data = (directory / filename).read_bytes()
    if hashlib.sha256(data).hexdigest() != SOURCES[filename]:
        raise ValueError("incorrect Unicode 15.0.0 source: " + filename)
    for line in data.decode("utf-8").splitlines():
        line = line.split("#", 1)[0].strip()
        if line:
            yield [field.strip() for field in line.split(";")]


def emit(stream, name, text):
    """Write one ASCII constant as implicitly concatenated bounded lines."""
    stream.write("\n" + name + " = (\n")
    line = ""
    for char in text:
        escaped = char.replace("\\", "\\\\").replace('"', '\\"')
        escaped = escaped.replace("\n", "\\n").replace("\t", "\\t")
        if len(line) + len(escaped) > 88:
            stream.write('    "' + line + '"\n')
            line = ""
        line += escaped
    if line:
        stream.write('    "' + line + '"\n')
    stream.write(")\n")


def integers(values, delta=False):
    """Pack hexadecimal integers, optionally as differences from the prior key."""
    previous = 0
    fields = []
    for value in values:
        fields.append(format(value - previous if delta else value, "x"))
        previous = value
    return " ".join(fields)


def packed_names(values):
    """Front-code sorted names without a dictionary or compression dependency."""
    previous = ""
    lines = []
    for value in values:
        common = 0
        while common < min(len(previous), len(value)) and previous[common] == value[common]:
            common += 1
        lines.append(format(common, "x") + ":" + value[common:])
        previous = value
    return "\n".join(lines)


def write_tables(
    starts, indices, records, decompositions, compositions, algorithmic, names, primary
):
    """Serialize the extracted tables using the portable lazy-decoding format."""
    with (DESTINATION / "_unicode15.py").open("w", encoding="ascii") as stream:
        stream.write(HEADER)
        emit(stream, "PROPERTY_STARTS", integers(starts, True))
        emit(stream, "PROPERTY_INDICES", integers(indices))
        emit(
            stream,
            "PROPERTY_RECORDS",
            "\n".join(
                "\t".join("" if part is None else str(part) for part in row) for row in records
            ),
        )
        emit(stream, "DECOMPOSITION_KEYS", integers([code for code, _ in decompositions], True))
        emit(stream, "DECOMPOSITION_VALUES", "\n".join(value[0] for _, value in decompositions))
        emit(stream, "COMPOSITION_KEYS", integers([key for key, _ in compositions], True))
        emit(stream, "COMPOSITION_VALUES", integers([value for _, value in compositions]))

    ordered_names = sorted(names)
    name_indices = {name: index for index, name in enumerate(ordered_names)}
    with (DESTINATION / "_unicode15_names.py").open("w", encoding="ascii") as stream:
        stream.write(HEADER)
        emit(
            stream,
            "ALGORITHMIC_RANGES",
            "\n".join(
                format(start, "x") + "\t" + format(end, "x") + "\t" + prefix
                for start, end, prefix in algorithmic
            ),
        )
        emit(stream, "NAMES", packed_names(ordered_names))
        emit(stream, "VALUES", "\n".join(integers(map(ord, names[name])) for name in ordered_names))
        emit(stream, "PRIMARY_CODEPOINTS", integers([code for code, _ in primary], True))
        emit(stream, "PRIMARY_INDICES", integers([name_indices[name] for _, name in primary]))


def require_pinned_host():
    """Reject a host with a different implementation or Unicode database."""
    if sys.implementation.name != "cpython" or sys.version_info[:3] != (3, 12, 12):
        raise SystemExit("generation requires CPython 3.12.12")
    if ucd.unidata_version != "15.0.0":
        raise SystemExit("generation requires Unicode 15.0.0")


def generate(directory):
    """Extract the complete current UCD without importing portable modules."""
    require_pinned_host()

    names = {}
    primary_names = []
    algorithmic = []
    records = []
    record_ids = {}
    starts = []
    indices = []
    decompositions = []
    compositions = []
    previous = None
    for code in range(0x110000):
        char = chr(code)
        record = (
            ucd.category(char),
            ucd.combining(char),
            ucd.bidirectional(char),
            ucd.east_asian_width(char),
            ucd.mirrored(char),
            ucd.decimal(char, None),
            ucd.digit(char, None),
            ucd.numeric(char, None),
        )
        if record != previous:
            if record not in record_ids:
                record_ids[record] = len(records)
                records.append(record)
            starts.append(code)
            indices.append(record_ids[record])
            previous = record
        raw = ucd.decomposition(char)
        if raw:
            fields = raw.split()
            compatibility = fields[0].startswith("<")
            parts = tuple(int(field, 16) for field in fields[compatibility:])
            decompositions.append((code, (raw, compatibility, parts)))
            if (
                not compatibility
                and len(parts) == 2
                and ucd.normalize("NFC", "".join(map(chr, parts))) == char
            ):
                compositions.append((parts[0] * 0x110000 + parts[1], code))
        name = ucd.name(char, None)
        if name is None or 0xAC00 <= code < 0xD7A4:
            continue
        prefix, separator, suffix = name.rpartition("-")
        if separator and suffix == format(code, "04X"):
            prefix += "-"
            if algorithmic and algorithmic[-1][2] == prefix and algorithmic[-1][1] + 1 == code:
                start, _, _ = algorithmic[-1]
                algorithmic[-1] = (start, code, prefix)
            else:
                algorithmic.append((code, code, prefix))
        else:
            names[name] = char
            primary_names.append((code, name))

    for _, alias, _ in source_records("NameAliases.txt", directory):
        names[alias] = ucd.lookup(alias)
    for name, _ in source_records("NamedSequences.txt", directory):
        names[name] = ucd.lookup(name)

    compositions.sort()
    write_tables(
        starts, indices, records, decompositions, compositions, algorithmic, names, primary_names
    )


def identifier_ranges():
    """Extract non-ASCII identifier and printable character ranges."""
    starts = []
    continuations = []
    printable = []
    for code in range(128, 0x110000):
        char = chr(code)
        for ranges, allowed in (
            (starts, char.isidentifier()),
            (continuations, ("a" + char).isidentifier()),
            (printable, ucd.category(char)[0] not in "CZ"),
        ):
            if allowed:
                if ranges and ranges[-1][1] == code - 1:
                    ranges[-1] = (ranges[-1][0], code)
                else:
                    ranges.append((code, code))
    return starts, continuations, printable


def emit_ranges(stream, header, footer, ranges, indent):
    """Write inclusive range pairs in a native language."""
    stream.write(header + "\n")
    line = indent
    for first, last in ranges:
        item = f"0x{first:X}, 0x{last:X},"
        if len(line) + len(item) > 100 and line != indent:
            stream.write(line.rstrip() + "\n")
            line = indent
        line += item + " "
    if line != indent:
        stream.write(line.rstrip() + "\n")
    stream.write(footer + "\n\n")


def generate_ts_printable(printable):
    """Write the shared TypeScript repr and str.isprintable predicate."""
    require_pinned_host()
    path = ROOT / "runtimes/ts/src/unicode15.ts"
    with path.open("w", encoding="ascii") as stream:
        stream.write("""// Generated by tools/generate_unicode.py; do not edit by hand.
// Source: CPython 3.12.12 Unicode 15.0.0 categories.
// Copyright Unicode, Inc. See https://www.unicode.org/terms_of_use.html.
// Inclusive non-ASCII ranges exclude all separator and control categories.

""")
        emit_ranges(stream, "const PRINTABLE_RANGES = [", "];", printable, "  ")
        stream.write("""/** Return Unicode 15.0.0 printable membership, including ASCII space. */
export function isPrintableCodePoint(code: number): boolean {
  if (code < 128) return code >= 32 && code < 127;
  let low = 0;
  let high = PRINTABLE_RANGES.length / 2;
  while (low < high) {
    const middle = (low + high) >>> 1;
    if (code < PRINTABLE_RANGES[middle * 2]) high = middle;
    else if (code > PRINTABLE_RANGES[middle * 2 + 1]) low = middle + 1;
    else return true;
  }
  return false;
}
""")


def generate_identifiers():
    """Generate allocation-free native Unicode membership helpers."""
    require_pinned_host()
    starts, continuations, printable = identifier_ranges()
    generate_ts_printable(printable)
    lua_path = ROOT / "runtimes/lua/diaspore/identifier.lua"
    with lua_path.open("w", encoding="ascii") as stream:
        stream.write(
            """-- Unicode 15.0.0 character predicates generated by tools/generate_unicode.py.
-- Source: CPython 3.12.12 identifiers and Unicode categories; do not edit by hand.
-- Copyright Unicode, Inc. See https://www.unicode.org/terms_of_use.html.
local M = {}

"""
        )
        emit_ranges(stream, "local xid_start = {", "}", starts, "  ")
        emit_ranges(stream, "local xid_continue = {", "}", continuations, "  ")
        emit_ranges(stream, "local printable = {", "}", printable, "  ")
        stream.write("""local function contains(ranges, code)
  local low, high = 1, #ranges // 2
  while low <= high do
    local middle = (low + high) // 2
    if code < ranges[middle * 2 - 1] then
      high = middle - 1
    elseif code > ranges[middle * 2] then
      low = middle + 1
    else
      return true
    end
  end
  return false
end

--- Return Python identifier membership using Unicode 15.0.0.
-- Keywords are identifiers; surrogates are not.
-- @param text Python string in the runtime's lax UTF-8 representation
-- @return boolean
function M.isidentifier(text)
  local first = true
  for _, code in utf8.codes(text, true) do
    if code < 128 then
      if not (code == 95 or (code >= 65 and code <= 90)
          or (code >= 97 and code <= 122)
          or (not first and code >= 48 and code <= 57)) then
        return false
      end
    elseif not contains(first and xid_start or xid_continue, code) then
      return false
    end
    first = false
  end
  return not first
end

--- Return Python printable membership using Unicode 15.0.0 categories.
-- ASCII space is printable; all other separator and control categories are not.
-- @param text Python string in the runtime's lax UTF-8 representation
-- @return boolean
function M.isprintable(text)
  for _, code in utf8.codes(text, true) do
    if code < 128 then
      if code < 32 or code == 127 then return false end
    elseif not contains(printable, code) then
      return false
    end
  end
  return true
end

return M
""")
    go_path = ROOT / "runtimes/go/interp/identifier.go"
    with go_path.open("w", encoding="ascii") as stream:
        stream.write("""// Code generated by tools/generate_unicode.py; DO NOT EDIT.
// Source: CPython 3.12.12 str.isidentifier, Unicode 15.0.0.
// Copyright Unicode, Inc. See https://www.unicode.org/terms_of_use.html.

package interp

""")
        emit_ranges(stream, "var pyXIDStart = [...]rune{", "}", starts, "\t")
        emit_ranges(stream, "var pyXIDContinue = [...]rune{", "}", continuations, "\t")
        stream.write("""func pyIdentifierContains(ranges []rune, code rune) bool {
\tlow, high := 0, len(ranges)/2
\tfor low < high {
\t\tmiddle := (low + high) / 2
\t\tif code < ranges[middle*2] {
\t\t\thigh = middle
\t\t} else if code > ranges[middle*2+1] {
\t\t\tlow = middle + 1
\t\t} else {
\t\t\treturn true
\t\t}
\t}
\treturn false
}

// pyIsIdentifier applies Python's Unicode 15.0.0 identifier rules, not keywords.
func pyIsIdentifier(text string) bool {
\tfirst := true
\tfor len(text) > 0 {
\t\tcode, size := pyDecodeRuneInString(text)
\t\tif code < 128 {
\t\t\tif !(code == '_' || (code >= 'A' && code <= 'Z') ||
\t\t\t\t(code >= 'a' && code <= 'z') ||
\t\t\t\t(!first && code >= '0' && code <= '9')) {
\t\t\t\treturn false
\t\t\t}
\t\t} else {
\t\t\tranges := pyXIDContinue[:]
\t\t\tif first {
\t\t\t\tranges = pyXIDStart[:]
\t\t\t}
\t\t\tif !pyIdentifierContains(ranges, code) {
\t\t\t\treturn false
\t\t\t}
\t\t}
\t\ttext = text[size:]
\t\tfirst = false
\t}
\treturn !first
}
""")


def main():
    """Regenerate portable Unicode data and native character helpers."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--ucd", type=Path, help="directory with pinned Unicode source files")
    parser.add_argument(
        "--identifiers-only",
        action="store_true",
        help="regenerate only native identifier and printable helpers",
    )
    args = parser.parse_args()
    if not args.identifiers_only:
        generate(args.ucd)
    generate_identifiers()


if __name__ == "__main__":
    main()
