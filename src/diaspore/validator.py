"""Validate bundle structure without dependencies at the runtime trust boundary.

The accepted structure matches the schema generated by ``diaspore.ir``.
"""

from __future__ import annotations

BIN_KINDS = frozenset(
    {
        "add",
        "sub",
        "mul",
        "div",
        "floordiv",
        "mod",
        "pow",
        "lshift",
        "rshift",
        "bitand",
        "bitor",
        "bitxor",
        "matmul",
    }
)
CMP_KINDS = frozenset({"eq", "ne", "lt", "le", "gt", "ge", "in", "notin", "is", "isnot"})
UNARY_KINDS = frozenset({"neg", "pos", "not", "invert"})
CONST_KINDS = frozenset({"int", "float", "str", "bytes", "bool", "none", "ellipsis", "complex"})


class BundleValidationError(ValueError):
    """Report a structural violation and its path within a bundle."""

    def __init__(self, msg: str, path: str):
        """Initialize the error with a message and bundle path."""
        self.path = path
        super().__init__(f"{path}: {msg}")


def _fail(msg: str, path: str):
    raise BundleValidationError(msg, path)


def _str(v, path):
    if not isinstance(v, str):
        _fail("expected string", path)


def _opt_str(v, path):
    if v is not None:
        _str(v, path)


def _stdlib_id(v, path):
    _str(v, path)
    if (
        len(v) != 71
        or not v.startswith("sha256:")
        or any(char not in "0123456789abcdef" for char in v[7:])
    ):
        _fail("expected sha256:<64 lowercase hexadecimal digits>", path)


def _bool(v, path):
    if not isinstance(v, bool):
        _fail("expected bool", path)


def _strs(v, path):
    if not isinstance(v, list) or any(not isinstance(x, str) for x in v):
        _fail("expected list of strings", path)


def _enum(v, allowed, path):
    if v not in allowed:
        _fail(f"invalid value {v!r}", path)


def _node(v, path):
    _validate_node(v, path)


def _opt_node(v, path):
    if v is not None:
        _validate_node(v, path)


def _nodes(v, path):
    if not isinstance(v, list):
        _fail("expected list of nodes", path)
    for i, x in enumerate(v):
        _validate_node(x, f"{path}[{i}]")


def _nodes1(v, path):
    _nodes(v, path)
    if not v:
        _fail("must not be empty", path)


def _nodes2(v, path):
    _nodes(v, path)
    if len(v) < 2:
        _fail("needs at least 2 elements", path)


def _const_v(v, path):
    if v is not None and not isinstance(v, (str, bool)):
        _fail("const v must be string, bool, or absent", path)


def _codepoints(v, path):
    if not isinstance(v, list):
        _fail("expected codepoints list", path)
    for i, point in enumerate(v):
        if type(point) is not int or not 0 <= point <= 0x10FFFF:
            _fail("expected Unicode codepoint integer", f"{path}[{i}]")


def _params(v, path):
    if not isinstance(v, dict):
        _fail("expected params object", path)
    _check_keys(
        v,
        set(),
        {"args", "posonly", "defaults", "vararg", "kwonly", "kwdefaults", "kwarg"},
        path,
        ln_ok=False,
    )
    _strs(v.get("args", []), f"{path}.args")
    posonly = v.get("posonly", 0)
    if type(posonly) is not int or not 0 <= posonly <= len(v.get("args", [])):
        _fail("expected positional-only count between 0 and len(args)", f"{path}.posonly")
    _nodes(v.get("defaults", []), f"{path}.defaults")
    _opt_str(v.get("vararg"), f"{path}.vararg")
    _strs(v.get("kwonly", []), f"{path}.kwonly")
    kwd = v.get("kwdefaults", [])
    if not isinstance(kwd, list):
        _fail("expected list", f"{path}.kwdefaults")
    for i, d in enumerate(kwd):
        _opt_node(d, f"{path}.kwdefaults[{i}]")
    _opt_str(v.get("kwarg"), f"{path}.kwarg")


def _kwargs(v, path):
    if not isinstance(v, list):
        _fail("expected list", path)
    for i, kw in enumerate(v):
        p = f"{path}[{i}]"
        if not isinstance(kw, dict):
            _fail("expected keyword object", p)
        _check_keys(kw, {"n", "v"}, {"n", "v"}, p, ln_ok=False)
        _opt_str(kw["n"], f"{p}.n")
        _node(kw["v"], f"{p}.v")


def _entries(v, path):
    if not isinstance(v, list):
        _fail("expected list", path)
    for i, e in enumerate(v):
        p = f"{path}[{i}]"
        if not isinstance(e, dict):
            _fail("expected entry object", p)
        _check_keys(e, {"k", "v"}, {"k", "v"}, p, ln_ok=False)
        _opt_node(e["k"], f"{p}.k")
        _node(e["v"], f"{p}.v")


def _parts(v, path):
    if not isinstance(v, list):
        _fail("expected list", path)
    for i, part in enumerate(v):
        p = f"{path}[{i}]"
        if not isinstance(part, dict):
            _fail("expected f-string part", p)
        if "s" in part:
            _check_keys(part, {"s"}, {"s", "codepoints"}, p, ln_ok=False)
            _str(part["s"], f"{p}.s")
            if "codepoints" in part:
                _codepoints(part["codepoints"], f"{p}.codepoints")
        else:
            _check_keys(part, {"v"}, {"v", "conv", "spec"}, p, ln_ok=False)
            _node(part["v"], f"{p}.v")
            if part.get("conv") is not None:
                _enum(part["conv"], {"r", "s", "a"}, f"{p}.conv")
            _opt_node(part.get("spec"), f"{p}.spec")


def _handlers(v, path):
    if not isinstance(v, list):
        _fail("expected list", path)
    for i, h in enumerate(v):
        p = f"{path}[{i}]"
        if not isinstance(h, dict):
            _fail("expected handler object", p)
        _check_keys(h, {"body"}, {"t", "name", "body"}, p, ln_ok=False)
        _opt_node(h.get("t"), f"{p}.t")
        _opt_str(h.get("name"), f"{p}.name")
        _nodes(h["body"], f"{p}.body")


def _items(v, path):
    if not isinstance(v, list):
        _fail("expected list", path)
    for i, it in enumerate(v):
        p = f"{path}[{i}]"
        if not isinstance(it, dict):
            _fail("expected with-item object", p)
        _check_keys(it, {"ctx"}, {"ctx", "name"}, p, ln_ok=False)
        _node(it["ctx"], f"{p}.ctx")
        _opt_node(it.get("name"), f"{p}.name")


def _names(v, path):
    if not isinstance(v, list):
        _fail("expected list", path)
    for i, n in enumerate(v):
        p = f"{path}[{i}]"
        if not isinstance(n, dict):
            _fail("expected import-name object", p)
        _check_keys(n, {"n", "alias"}, {"n", "alias"}, p, ln_ok=False)
        _str(n["n"], f"{p}.n")
        _str(n["alias"], f"{p}.alias")


def _name_node(v, path):
    _node(v, path)
    if v.get("op") != "name":
        _fail("expected a name node", path)


# op -> (required fields, optional fields, {field: checker})
_SHAPES: dict[str, tuple[set, set, dict]] = {
    "const": (
        {"t"},
        {"v", "re", "im", "codepoints"},
        {"t": lambda v, p: _enum(v, CONST_KINDS, p), "v": _const_v,
         "re": _opt_str, "im": _opt_str, "codepoints": _codepoints},
    ),
    "name": ({"id"}, set(), {"id": _str}),
    "attr": ({"o", "n"}, set(), {"o": _node, "n": _str}),
    "index": ({"o", "k"}, set(), {"o": _node, "k": _node}),
    "slicelit": (
        set(),
        {"lower", "upper", "step"},
        {"lower": _node, "upper": _node, "step": _node},
    ),
    "starred": ({"v"}, set(), {"v": _node}),
    "call": ({"f"}, {"args", "kw"}, {"f": _node, "args": _nodes, "kw": _kwargs}),
    "binop": (
        {"kind", "l", "r"},
        set(),
        {"kind": lambda v, p: _enum(v, BIN_KINDS, p), "l": _node, "r": _node},
    ),
    "unary": ({"kind", "v"}, set(), {"kind": lambda v, p: _enum(v, UNARY_KINDS, p), "v": _node}),
    "boolop": (
        {"kind", "values"},
        set(),
        {"kind": lambda v, p: _enum(v, {"and", "or"}, p), "values": _nodes2},
    ),
    "compare": (
        {"left", "ops", "comps"},
        set(),
        {
            "left": _node,
            "ops": lambda v, p: (
                _fail("needs at least 1 op", p)
                if not isinstance(v, list) or not v
                else [_enum(o, CMP_KINDS, f"{p}[{i}]") for i, o in enumerate(v)]
            ),
            "comps": _nodes1,
        },
    ),
    "cond": ({"test", "then", "else"}, set(), {"test": _node, "then": _node, "else": _node}),
    "list": (set(), {"elts"}, {"elts": _nodes}),
    "tuple": (set(), {"elts"}, {"elts": _nodes}),
    "set": (set(), {"elts"}, {"elts": _nodes}),
    "dict": (set(), {"entries"}, {"entries": _entries}),
    "fstring": ({"parts"}, set(), {"parts": _parts}),
    "func": (
        {"name", "params", "body"},
        {"gen", "coro", "asyncgen", "annotation_scope", "locals", "gdecl", "ndecl"},
        {
            "name": _str,
            "gen": _bool,
            "coro": _bool,
            "asyncgen": _bool,
            "annotation_scope": _bool,
            "params": _params,
            "locals": _strs,
            "gdecl": _strs,
            "ndecl": _strs,
            "body": _nodes,
        },
    ),
    "yield": (set(), {"v"}, {"v": _node}),
    "yieldfrom": ({"v"}, set(), {"v": _node}),
    "namedexpr": ({"target", "v"}, set(), {"target": _name_node, "v": _node}),
    "expr": ({"v"}, set(), {"v": _node}),
    "assign": ({"targets", "v"}, set(), {"targets": _nodes1, "v": _node}),
    "augassign": (
        {"target", "kind", "v"},
        set(),
        {"target": _node, "kind": lambda v, p: _enum(v, BIN_KINDS, p), "v": _node},
    ),
    "if": ({"test", "then"}, {"orelse"}, {"test": _node, "then": _nodes, "orelse": _nodes}),
    "while": ({"test", "body"}, {"orelse"}, {"test": _node, "body": _nodes, "orelse": _nodes}),
    "for": (
        {"target", "iter", "body"},
        {"orelse"},
        {"target": _node, "iter": _node, "body": _nodes, "orelse": _nodes},
    ),
    "break": (set(), set(), {}),
    "continue": (set(), set(), {}),
    "pass": (set(), set(), {}),
    "return": (set(), {"v"}, {"v": _node}),
    "class": (
        {"name", "body"},
        {"bases", "kwargs", "binding"},
        {"name": _str, "bases": _nodes, "body": _nodes, "kwargs": _kwargs, "binding": _str},
    ),
    "raise": (set(), {"exc", "cause"}, {"exc": _node, "cause": _node}),
    "try": (
        {"body"},
        {"handlers", "orelse", "finalbody", "star"},
        {
            "body": _nodes,
            "handlers": _handlers,
            "orelse": _nodes,
            "finalbody": _nodes,
            "star": _bool,
        },
    ),
    "with": ({"items", "body"}, set(), {"items": _items, "body": _nodes}),
    "import": (
        {"module"},
        {"alias", "bind"},
        {"module": _str, "alias": _opt_str, "bind": lambda x, p: _enum(x, {"root", "none"}, p)},
    ),
    "importfrom": ({"module", "names"}, set(), {"module": _str, "names": _names}),
    "del": ({"targets"}, set(), {"targets": _nodes}),
}
_SHAPES["funcexpr"] = _SHAPES["func"]


def _check_keys(obj: dict, required: set, allowed: set, path: str, ln_ok: bool = True):
    missing = required - obj.keys()
    if missing:
        _fail(f"missing field(s): {', '.join(sorted(missing))}", path)
    extra = set(obj.keys()) - allowed - ({"op", "ln"} if ln_ok else set())
    if extra:
        _fail(f"unknown field(s): {', '.join(sorted(extra))}", path)
    if ln_ok and "ln" in obj and obj["ln"] is not None and not isinstance(obj["ln"], int):
        _fail("ln must be an integer", f"{path}.ln")


def _validate_node(node, path: str):
    if not isinstance(node, dict):
        _fail("expected a node object", path)
    op = node.get("op")
    if op not in _SHAPES:
        _fail(f"unknown op {op!r}", path)
    required, optional, checkers = _SHAPES[op]
    _check_keys(node, required, required | optional, f"{path}({op})")
    for field, checker in checkers.items():
        if field in node:
            checker(node[field], f"{path}({op}).{field}")
    if op == "const" and "codepoints" in node:
        if node["t"] != "str" or not isinstance(node.get("v"), str):
            _fail("codepoints requires a string constant", path)


def validate_bundle(data) -> None:
    """Validate the structure of an untrusted bundle.

    Args:
        data: Decoded bundle JSON.

    Raises:
        BundleValidationError: The bundle contains a structural violation.
    """
    if not isinstance(data, dict):
        _fail("bundle must be an object", "$")
    _check_keys(
        data, {"diaspore", "main", "modules"}, {"diaspore", "main", "modules", "stdlib"},
        "$", ln_ok=False,
    )
    if data["diaspore"] != 1:
        _fail("unsupported diaspore version", "$.diaspore")
    _str(data["main"], "$.main")
    if "stdlib" in data:
        _stdlib_id(data["stdlib"], "$.stdlib")
    if not isinstance(data["modules"], dict):
        _fail("modules must be an object", "$.modules")
    if data["main"] not in data["modules"]:
        _fail("main module missing from modules", "$.main")
    for name, mod in data["modules"].items():
        p = f"$.modules[{name}]"
        if not isinstance(mod, dict):
            _fail("expected module object", p)
        _check_keys(mod, {"name", "file", "body"}, {"name", "file", "body", "src"}, p, ln_ok=False)
        _str(mod["name"], f"{p}.name")
        _str(mod["file"], f"{p}.file")
        _nodes(mod["body"], f"{p}.body")
        if mod.get("src") is not None:
            _strs(mod["src"], f"{p}.src")
